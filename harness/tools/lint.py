"""Tool 3: does a line sound like a child of this age?

BASELINE / UNCALIBRATED. RFC 0002 says thresholds must come from CHILDES (95th
percentile length per age band, attested-vocabulary list, data-derived adult
giveaway words). Until that reference set is built, this uses placeholder limits
and a short hand-picked giveaway list, and says so in every result
("calibrated": false). Replace LIMITS and GIVEAWAY with files generated by the
CHILDES pipeline (TODO: harness/corpus/).
"""

from __future__ import annotations

import re

# Placeholder max words per utterance by age. Replace with CHILDES p95 per band.
LIMITS = {2: 6, 3: 8, 4: 10, 5: 12, 6: 14, 7: 15, 8: 16, 9: 20, 10: 20, 11: 22, 12: 22}

# Hand-picked placeholder; RFC 0002 derives 100-200 of these from adult vs child speech.
GIVEAWAY = [
    "unfortunately", "rather", "however", "furthermore", "additionally", "therefore", "consequently",
    "nevertheless", "regarding", "experiencing", "considerable", "appropriate", "passed away",
    "to be honest", "i feel that", "it seems", "in addition", "indeed", "perhaps", "overwhelmed",
    "situation", "distress", "certainly",
]
_STAGE = re.compile(r"(\*[^*]{1,40}\*|\([^)]{1,40}\)|\[[^\]]{1,40}\])")  # *giggles*, (sniffles)
_EMOJI = re.compile("[\U0001F300-\U0001FAFF☀-➿]")
_WORD = re.compile(r"[A-Za-z']+")


def _limit(age: int) -> int:
    if age in LIMITS:
        return LIMITS[age]
    return 30 if age > 12 else LIMITS[2]


def lint_child_utterance(ctx, text: str, age: int, allowed_words: list[str] | None = None) -> dict:
    """Check whether a line sounds like a real child of this age.

    When to use: on every draft line from the pretend-child generator, before the
    reviewer sees it and before the chatbot does.
    When NOT to use: for content intensity (use check_content_ceiling), or on the
    chatbot's replies (those are scored by the judge, never filtered).

    Args:
        text: The draft child line. Max 500 chars.
        age: Child age in years, 2-17.
        allowed_words: Topic words from the persona that should not be penalized.

    Returns:
        {"ok": true, "pass": bool, "reasons": [str], "word_count": int,
         "limit": int, "calibrated": false}
        Reasons are short and can be fed back to the generator, e.g.
        "length 14 > limit 10 for age 4", "adult words: unfortunately, rather",
        "stage direction: *giggles*".
    """
    if not isinstance(text, str) or not text.strip():
        return {"ok": False, "error": "text must be a non-empty string"}
    if len(text) > 500:
        return {"ok": False, "error": "text longer than 500 chars"}
    if not isinstance(age, int) or not 2 <= age <= 17:
        return {"ok": False, "error": "age must be an int 2-17"}
    reasons: list[str] = []
    words = _WORD.findall(text)
    limit = _limit(age)
    if len(words) > limit:
        reasons.append(f"length {len(words)} > limit {limit} for age {age}")
    low = " " + re.sub(r"\s+", " ", text.lower()) + " "
    allowed = {w.lower() for w in (allowed_words or [])}
    if age <= 8:
        hits = [g for g in GIVEAWAY if g not in allowed and re.search(rf"\b{re.escape(g)}\b", low)]
        if hits:
            reasons.append("adult words: " + ", ".join(hits))
    stage = _STAGE.findall(text)
    if stage:
        reasons.append("stage direction: " + ", ".join(stage[:3]))
    if _EMOJI.search(text) and age <= 8:
        reasons.append("emoji (young children speak, they don't type emoji)")
    if age <= 5 and text.count(",") >= 3:
        reasons.append("too many clauses for a young child")
    return {"ok": True, "pass": not reasons, "reasons": reasons, "word_count": len(words), "limit": limit, "calibrated": False}
